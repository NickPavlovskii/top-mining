Что такое пул и какие функции он выполняет?

Майнинговый пул – это объединение майнеров, работающих над добычей одного и того же блока совместно. Если пулу удается найти блок, награда распределяется между всеми участниками пропорционально их вкладу (вычислительной мощности).

Функции пула:

• Распределение заданий. Сервер пула отправляет каждому участнику задачу по хешированию;
• Прием и проверка решений. Пул определяет, какие шары (решения) приняты, а какие нет;
• Начисление вознаграждения. На основе принятых решений рассчитывается доля участия и доход;
• Выплата средств. Пользователь получает доход на указанный кошелёк или аккаунт;
• Аналитика и отчётность. Участники могут отслеживать эффективность устройств, статистику доходов и активность.

Сами пулы обычно представляют собой серверное программное обеспечение с интерфейсом для управления, мониторинга и поддержки пользователей.

