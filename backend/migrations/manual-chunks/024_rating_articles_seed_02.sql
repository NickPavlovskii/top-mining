Почему асики стоят так дорого?

Можно назвать несколько причин подобной политики ценообразования в майнинговой отрасли:

Узкая специализация и сложность производства. Асик – это устройство, спроектированное исключительно под выполнение одной задачи: добычу криптовалюты (например, Биткоина с алгоритмом SHA-256). Разработка чипов требует значительных инвестиций: от проектирования до тестирования и запуска в массовое производство. Производственные линии на фабриках стоят миллионы долларов, и не каждая компания может позволить себе подобное;

Ограниченное количество производителей. Основными игроками являются Bitmain, MicroBT, Canaan и несколько других. Такая ограниченность создает низкую конкуренцию, что позволяет производителям держать высокие цены, особенно на топовые модели;

Высокий спрос при ограниченном предложении. Когда курс криптовалюты растет, увеличивается интерес к майнингу. Это вызывает всплеск спроса на оборудование, а предложение не всегда успевает за ним. Итог – рост цен, особенно на популярные модели;

Сложности с логистикой и пошлинами. Большинство ASIC-устройств производятся в Китае. При международной доставке добавляются таможенные пошлины, налоги, комиссии – все это включается в конечную цену.

Почему новые ASIC-майнеры всегда дороже?

Наверняка вы успели заметить, что как только новинка появляется на рынке, ее стоимость значительно выше, чем у конкурирующих предложений. Постараемся объяснить природу данного явления:

Улучшенные характеристики. Новые модели отличаются большей энергоэффективностью и хешрейтом. К примеру, если старый майнер выдает 190 TH/s при 3,5 кВт, то новый может давать 240 TH/s при том же или меньшем энергопотреблении. Это позволяет быстрее окупить вложения, отсюда и высокий ценник;

«Эффект первого». Владельцы первых партий новых асиков получают конкурентное преимущество: они начинают добычу с более высокой эффективностью, пока сложность сети не адаптировалась. Производители используют это, выставляя премиальную цену за доступ к новейшему оборудованию;

Ограниченные тиражи на старте. На первых порах производитель выпускает ограниченное количество устройств, и часто их выкупают оптовики или крупные пулы. Чем меньше предложение, тем выше цена.

