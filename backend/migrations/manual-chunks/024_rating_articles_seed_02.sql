Все, что полезно знать о майнинге на процессорах

Краткая история CPU-майнинга:

• 2009–2011: первые годы биткойна – майнинг осуществляется только на CPU;
• 2011–2013: появились GPU-майнеры (видеокарты), вытеснив CPU из биткойн-майнинга;
• С 2013: ASIC-устройства (специализированное оборудование) стали доминировать в добыче большинства монет;
• 2018–2024: рост популярности альтернативных криптовалют, устойчивых к ASIC, возродил интерес к CPU-майнингу (например, Monero, VerusCoin, Raptoreum).

Несмотря на существенный рост сложности добычи и параллельное сокращение доходности, майнинг на процессорах сегодня все еще существует. Подобное возможно благодаря наличию преимуществ работы в таком формате:

Низкий порог входа. Можно начать майнинг даже с обычного домашнего ПК или ноутбука (хотя эффективность будет низкой);

Устойчивость к асикам. Некоторые криптовалюты (например, Yadacoin и VerusCoin) используют алгоритмы, которые специально спроектированы так, чтобы быть неэффективными на асиках и GPU, защищая CPU-майнеров;

Тихая работа и низкое энергопотребление. Процессоры потребляют меньше энергии и не требуют шумных систем охлаждения, как видеокарты. Поэтому запустить ферму можно в домашних условиях;

Гибкость. Легко переключиться между монетами. Также CPU всегда может использоваться для других задач.

Правда, не обходится и без недостатков, некоторые из которых могут оказаться весьма существенными:

Низкая доходность. CPU-майнинг крайне неэффективен для большинства популярных монет. Заработок зачастую едва покрывает расходы на электричество;

Износ оборудования. Постоянная нагрузка 24/7 увеличивает износ процессора и материнской платы;

Ограниченный выбор монет. Только небольшое количество криптовалют (например, Haven и Raptoreum) выгодно майнить на CPU.

А какие технические особенности важно учитывать при намерении начать добычу криптовалют с помощью процессоров? Список основных характеристик выглядит следующим образом:

• Количество ядер и потоков (чем больше, тем лучше) – многие алгоритмы, как правило, многопоточные;
• L3-кэш. Особенно важен для алгоритмов вроде RandomX и GhostRider. Чем больше кэш – тем выше доходность;
• Энергопотребление. Важно учитывать эффективность: сколько хэшей в секунду на каждый ватт;
• Разгон и охлаждение. Майнинг нагружает CPU на 100%: требуется надежное охлаждение, желательно башенный кулер или система жидкостного охлаждения.

