Снижение риска в нестабильном рынке. Если курс биткоина резко падает, цены на новое оборудование могут остаться высокими, однако «вторичка» дешевеет быстрее. Это делает ее более привлекательной при нестабильности;

Расширение мощностей. Иногда проще и дешевле нарастить мощности с помощью подержанных устройств, чем дожидаться новых поставок с заводов;

