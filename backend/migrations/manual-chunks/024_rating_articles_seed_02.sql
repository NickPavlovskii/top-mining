2 место: Antminer T21

Antminer T21 — это представитель профессиональных майнеров SHA-256, созданный для добычи Биткоина. Он выдает до 190 TH/s при потреблении 3610 Вт, что делает его одним из самых популярных ASIC-устройств своего класса.

Одной из особенностей модели стало трехфазное питание. Такой формат подключения часто используется на крупных майнинг-фермах и дата-центрах, однако менее удобен для частных майнеров. Именно эта особенность делает стоимость Antminer T21 ниже, чем у большинства аналогов с сопоставимым хешрейтом — модель ориентирована на профессиональный рынок, что снижает спрос со стороны домашних пользователей.

