Сегодня использование легенды уже не совсем оправдано, даже если майнер является обладателем так называемой «бесплатной» розетки. Любая альтернатива, выпущенная после 2018 года, будет зарабатывать больше, поэтому Antminer S9 можно смело назвать прошлым. Но это не отменяет того факта, что 9-я линейка является самым популярным асиком для майнинга за все время существования отрасли добычи криптовалют.

