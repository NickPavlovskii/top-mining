Почему сложно точно оценить хешрейт по странам?

На первый взгляд, кажется простой задачей составить рейтинг стран по объему майнинга, опираясь на данные с пулов и энергетических компаний.

Однако есть серьезные сложности, мешающие точной аналитике:

1. Облачные и мультигеографические пулы. Большинство майнеров подключаются к международным пулам, которые распределяют мощность между дата-центрами по всему миру. Поэтому реальное географическое расположение оборудования часто не раскрывается;

2. Анонимность участников. Майнеры в странах с полулегальным, молодым законодательством или серым статусом (например, Россия или Иран) не афишируют свое присутствие. Использование прокси и VPN также затрудняет отслеживание;

3. Перемещение оборудования. Многие компании могут переносить майнинг-фермы из одной страны в другую в зависимости от тарифов, регулирования или технических сбоев. Таким образом, данные по хешрейту быстро устаревают;

4. Домашний майнинг. Домашние майнеры, особенно в странах с субсидированными тарифами, в статистику чаще всего не попадают вовсе.

