Базовыми монетами, добываемыми на Scrypt, являются мемкоин Dogecoin и Litecoin. Данный актив можно получать при использовании процессоров, видеокарт и асиков: часто задействуется так называемый дуал-майнинг – одновременное получение LTC и DOGE для диверсификации рисков.

А еще Догикоин очень нравится Илону Маску, который не упускает возможности оказать спекулятивное воздействие на токен. Например, однажды новость о возможности оплаты мерча Tesla с помощью Dogecoin привела к росту курса в моменте на 25% – для этого потребовался всего один твит. Подобное явление можно считать как преимуществом (интерес публичной персоны к крипте всегда выгоден инвесторам), так и недостатком (все же от спекулятивных форматов стоит держаться подальше).

