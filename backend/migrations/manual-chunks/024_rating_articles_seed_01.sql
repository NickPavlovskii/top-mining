Что такое облачный майнинг?

Облачный майнинг – это аренда вычислительной мощности у специализированных дата-центров. Пользователь платит за хэшрейт, а доход от добытых монет поступает на его кошелек. Все операции с оборудованием (охлаждение, настройка, обслуживание) берет на себя провайдер. Это позволяет майнить без покупки оборудования, настройки ферм и затрат на электроэнергию. Человек просто приобретает контракт, указывает кошелек для выплат – и получает доход пропорционально купленной мощности.

